"""Write experiments/INDEX.md: what every script in experiments/ and papers/ is, and whether the manuscript uses it.

The purpose of each script is the start of its docstring (or first comment for shell scripts). The role comes
from the PIPELINE table below, which is maintained by hand; any script not listed there is marked "not used for the
manuscript numbers" so that nothing is silently assumed to be part of the pipeline.
Usage (from the repo root): python3 experiments/build_code_index.py
"""
import ast
import re
from pathlib import Path

E, P = Path("experiments"), Path("papers")

# role -> scripts, in the order they are used
PIPELINE = [
    ("1. Shared code", ["synthetic_data_eval.py", "run_hillstrom.py", "run_criteo.py", "run_nomao.py"]),
    ("2. Experiments rerun with seeded CTGAN (October 2026)", [
        "run_full_metrics_hillstrom_criteo.py", "run_full_metrics_benchmark_datasets.py", "launch_nomao_fullmetrics.sh",
        "run_fullmetrics_nomao_driver.sh", "_fullmetrics_nomao_worker.py", "run_dose_response_bank_marketing.py",
        "run_dose_response_nomao.py", "_dose_response_nomao_worker.py", "run_dose_response_bank_alpha.py",
        "run_ci_multi_classifier.py", "measure_class_distribution_all_generators.py", "run_nomao_sparse_ci.py",
        "run_tstr_lowdata.py", "launch_ctgan_reruns.sh"]),
    ("3. CTGAN reproducibility checks", ["run_ctgan_seed_check.py", "run_ctgan_refit_variance.py"]),
    ("4. Experiments without CTGAN, or already seeding PyTorch (not rerun)", [
        "run_missing_baselines_hillstrom_criteo.py", "run_balanced_baseline.py", "run_tabddpm_databricks.py",
        "run_great_hillstrom_databricks.py", "run_modernllm_hillstrom_databricks.py", "run_modernllm_all_databricks.py",
        "run_great_telco_databricks.py", "run_great_alpha_sweep_german_databricks.py", "run_great_alpha_sweep_hillstrom_databricks.py",
        "run_great_alpha_sweep_telco_databricks.py", "run_great_databricks.py", "measure_tabddpm_class_distribution.py",
        "check_bank_duration.py"]),
    ("5. Statistics, tables and checks", ["compute_statistics.py", "format_control_tables.py", "verify_manuscript_numbers.py"]),
    ("6. Figures", ["make_plots_paper2.py", "make_plot_missing_baselines.py", "make_plot_dose_response.py",
                    "make_plot_dose_response_combined.py", "make_plot_gain_vs_positive_rate.py", "make_plot_fig10_modernllm.py"]),
    ("7. Records and documents", ["build_provenance_index.py", "write_run_manifest.py", "build_code_index.py"]),
]
PAPERS = {"build_docx.py": "Builds the Google-Docs-friendly .docx from the markdown.",
          "renumber_references.py": "Renumbers references by first citation."}


OVERRIDES = {
    "synthetic_data_eval.py": "Shared functions: data loaders, the GaussianCopula, CTGAN (PyTorch seeded, CPU) and SMOTE generators, classifier training and metrics.",
    "run_ci_multi_classifier.py": "10-seed, four-classifier runs (Gradient Boosting, Logistic Regression, Random Forest, MLP) on Hillstrom and Criteo with GaussianCopula, CTGAN and SMOTE.",
}


def purpose(path):
    if path.name in OVERRIDES:
        return OVERRIDES[path.name]
    txt = path.read_text(errors="ignore")
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(txt)) or ""
        except SyntaxError:
            doc = ""
        para = doc.split("\n\n")[0] if doc else ""
        text = re.sub(r"\s+", " ", re.sub(r"[=\-]{3,}", "", para)).strip()
        return (text[:230] + "...") if len(text) > 230 else (text or "(no docstring)")
    line = next((l.lstrip("# ").strip() for l in txt.splitlines()[1:] if l.startswith("#")), "")
    return line or "(no comment)"


listed = {s for _, group in PIPELINE for s in group}
out = ["# Code index", "",
       "Generated by `experiments/build_code_index.py`. Each purpose is the first paragraph (shortened) of the script's own docstring.",
       "`papers/paper2-electronics-provenance.md` maps every table, figure and number to the files and scripts that produced it,",
       "and `results/RUN_MANIFEST.md` records the setup and a checksum for each rerun result file.", ""]
for title, group in PIPELINE:
    out += [f"## {title}", "", "| Script | Purpose |", "|---|---|"]
    for s in group:
        f = E / s
        out.append(f"| `{s}` | {purpose(f) if f.exists() else '**MISSING FILE**'} |")
    out.append("")
others = sorted(p.name for p in list(E.glob("*.py")) + list(E.glob("*.sh")) if p.name not in listed)
out += ["## 8. Not used for the manuscript numbers", "",
        "Earlier or exploratory scripts. They are kept for history. None of them produces a number, table or figure in the current manuscript.", "",
        "| Script | Purpose |", "|---|---|"]
out += [f"| `{s}` | {purpose(E / s)} |" for s in others]
out += ["", "## Documents (`papers/`)", "", "| Script | Purpose |", "|---|---|"]
out += [f"| `{k}` | {v} |" for k, v in PAPERS.items()]
(E / "INDEX.md").write_text("\n".join(out) + "\n")
missing = [s for s in listed if not (E / s).exists()]
print("wrote experiments/INDEX.md;", len(listed), "indexed,", len(others), "not used;", "missing:", missing or "none")
