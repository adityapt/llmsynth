"""
Measure the actual positive rate in synthetic rows generated by GaussianCopula,
CTGAN, and SMOTE (companion to measure_tabddpm_class_distribution.py, which
covers TabDDPM). Fills Table 2 of paper2-empirical.md with a real, saved,
reproducible 5-seed measurement — the previous version of this table had no
saved artifact for these three generators and its ±CI figures could not be
verified (see the provenance note in the paper).

Same protocol as measure_tabddpm_class_distribution.py: same seeds, same
N_CAP/N_SYN, same stratified 80/20 split, mean ± population std across seeds.

Output: results/synthetic_class_distribution_5seed.csv
"""
import warnings
warnings.filterwarnings("ignore")
import sys
sys.path.insert(0, '.')

import numpy as np
import pandas as pd
from pathlib import Path
from sklearn.model_selection import train_test_split

from experiments.synthetic_data_eval import (
    RESULTS_DIR, generate_ctgan, generate_gaussian_copula, generate_smote,
)
from experiments.run_hillstrom import load_hillstrom
from experiments.run_criteo import load_criteo_uplift

TARGET = "target"
SEEDS  = [42, 123, 7, 2024, 999]
N_CAP  = 10_000
N_SYN  = 8_000  # alpha=1.0, same as main experiments

datasets = [
    ("Hillstrom Email", *load_hillstrom()[:2]),
    ("Criteo Display", *load_criteo_uplift()[:2]),
]

rows = []
for name, df_full, target in datasets:
    real_pos = df_full[target].mean()
    print(f"\n{'='*60}\n{name}: real positive rate = {real_pos*100:.2f}%\n{'='*60}", flush=True)

    per_gen_rates = {"GaussianCopula": [], "CTGAN": [], "SMOTE": []}
    for seed in SEEDS:
        df_sample = df_full.sample(min(N_CAP, len(df_full)), random_state=seed).reset_index(drop=True)
        df_train, _ = train_test_split(df_sample, test_size=0.2, random_state=seed,
                                        stratify=df_sample[target])
        X_tr = df_train.drop(columns=[target])
        y_tr = df_train[target]

        print(f"  seed={seed}:", end="", flush=True)

        try:
            syn = generate_gaussian_copula(df_train, target, N_SYN, "classification")
            rate = pd.to_numeric(syn[target], errors="coerce").fillna(0).mean() * 100
            per_gen_rates["GaussianCopula"].append(rate)
            print(f" GC={rate:.2f}%", end="", flush=True)
        except Exception as e:
            print(f" GC FAIL({str(e)[:60]})", end="", flush=True)

        try:
            syn = generate_ctgan(df_train, target, N_SYN, "classification")
            rate = pd.to_numeric(syn[target], errors="coerce").fillna(0).mean() * 100
            per_gen_rates["CTGAN"].append(rate)
            print(f"  CTGAN={rate:.2f}%", end="", flush=True)
        except Exception as e:
            print(f"  CTGAN FAIL({str(e)[:60]})", end="", flush=True)

        try:
            syn = generate_smote(X_tr, y_tr, N_SYN)
            rate = pd.to_numeric(syn[target], errors="coerce").fillna(0).mean() * 100
            per_gen_rates["SMOTE"].append(rate)
            print(f"  SMOTE={rate:.2f}%", flush=True)
        except Exception as e:
            print(f"  SMOTE FAIL({str(e)[:60]})", flush=True)

    row = {"dataset": name, "real_positive_rate": round(real_pos * 100, 4)}
    for gen, rates in per_gen_rates.items():
        if rates:
            row[f"{gen}_mean"] = round(float(np.mean(rates)), 4)
            row[f"{gen}_std"] = round(float(np.std(rates)), 4)
            row[f"{gen}_n_seeds"] = len(rates)
    rows.append(row)
    pd.DataFrame(rows).to_csv(RESULTS_DIR / "synthetic_class_distribution_5seed.csv", index=False)

print(f"\nSaved: {RESULTS_DIR / 'synthetic_class_distribution_5seed.csv'}")
print(pd.DataFrame(rows).to_string(index=False))
